-- 직급 2종의 이름을 실제 직위명으로 맞춘다 (2026-08-24 사용자 확인).
--
-- 무엇이 틀렸나: 인원 시드를 사내 조직 SQL에서 옮길 때 원본 **직위 코드 이름**을
-- 그대로 살린 칸이 둘 있었다 — VICE_PRESIDENT를 '부사장', MANAGER를 '매니저'로.
-- 실제 직위명은 각각 **부대표**·**과장**이고, 둘 다 보유자가 1명씩이다
-- (부대표 천용우 · 과장 김도한). 계수(1.8 · 1.0)는 그대로다 — 이름만 틀렸다.
--
-- 왜 여기서 수렴시키나: 인원 시드 로더는 조직 노드가 이미 있으면 적재를 건너뛰므로
-- (`ON CONFLICT DO NOTHING`도 이름을 고치지 않는다) 이미 적재된 DB는 시드 파일만
-- 고쳐도 옛 이름을 계속 들고 있다. 참조 데이터의 '정정'을 마이그레이션으로 수렴시키는
-- 것은 V4·V10의 선례다. 빈 DB에서는 대상 행이 없어 아무 일도 하지 않고, 이어서
-- 시드가 교정된 이름으로 넣는다.
--
-- id로 짚지 않고 이름으로 짚는 이유: 직급 id는 명시 id지만(부록 B) 운영 중 화면에서
-- 신설·삭제가 가능해(E4-1·E4-3) 이 마이그레이션이 도는 DB의 9번이 반드시 그 직급이라고
-- 단정할 수 없다. 이름은 지금 그 값을 가진 행만 정확히 집는다.
UPDATE grades SET name = '부대표' WHERE name = '부사장';
UPDATE grades SET name = '과장' WHERE name = '매니저';
